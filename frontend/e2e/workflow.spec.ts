import { test, expect, type APIRequestContext, type Page } from '@playwright/test'

const initial = 'synthetic-e2e-initial-passphrase'
const rotated = 'synthetic-e2e-rotated-passphrase'
async function checked(response: Awaited<ReturnType<APIRequestContext['post']>>) {
  expect(response.ok(), `HTTP ${response.status()}: ${await response.text()}`).toBeTruthy()
  return response.json()
}
async function openReport(page: Page, description: string) {
  await page.goto('/')
  await page.getByRole('searchbox').fill(description)
  await page.locator('.incident-card').filter({ hasText: description }).first().click()
}

test('real browser worker → clarification → independent release → execution → verification', async ({ browser, playwright }) => {
  const admin = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:5179' })
  await checked(await admin.post('/api/v1/setup', { data: { organization_name: 'Synthetic Browser Test', site_name: 'Acceptance Plant', name: 'Test Administrator', email: 'admin@example.test', password: initial } }))
  const asset = await checked(await admin.post('/api/v1/assets', { data: { code: 'BROWSER-01', name: 'Acceptance press', area: 'Test Bay', criticality: 'high' } }))
  for (const role of ['worker', 'engineer']) await checked(await admin.post('/api/v1/users', { data: { name: role === 'engineer' ? 'Priyanshu Chauhan' : 'Acceptance Worker', email: `${role}@example.test`, role, password: initial } }))
  const worker = await browser.newContext()
  const engineer = await browser.newContext()
  const workerPage = await worker.newPage()
  const engineerPage = await engineer.newPage()
  const signIn = async (page: Page, role: string) => {
    await page.goto('/')
    await page.getByLabel('Work email', { exact: true }).fill(`${role}@example.test`)
    await page.getByLabel('Password', { exact: true }).fill(initial)
    await page.getByRole('button', { name: 'Sign in securely', exact: true }).click()
    await expect(page.getByText('Your administrator requires a password change before operational work can resume.')).toBeVisible()
    const form = page.locator('form').filter({ has: page.getByRole('button', { name: 'Change password & revoke other sessions', exact: true }) })
    await form.getByLabel('Current password', { exact: true }).fill(initial)
    await form.getByLabel('New password', { exact: true }).fill(rotated)
    await form.getByRole('button', { name: 'Change password & revoke other sessions', exact: true }).click()
    await expect(page.getByRole('button', { name: role === 'engineer' ? 'Work register' : 'My notebook', exact: true })).toBeVisible()
  }
  await signIn(workerPage, 'worker')
  await signIn(engineerPage, 'engineer')
  await workerPage.getByRole('button', { name: 'New field report', exact: true }).first().click()
  const assetSelect = workerPage.locator('select').filter({ hasText: 'BROWSER-01' }).first()
  await expect(assetSelect).toBeVisible()
  await assetSelect.selectOption(asset.id)
  const original = 'A protective alarm stopped the press during the acceptance test.'
  await workerPage.getByLabel('What did you observe?', { exact: true }).fill(original)
  await workerPage.getByLabel('Production / operational impact', { exact: true }).fill('Test line stopped; duration not yet established.')
  await workerPage.getByRole('button', { name: 'Submit source report', exact: true }).click()
  await expect(workerPage.getByRole('heading', { name: 'The field observation', exact: true })).toBeVisible()
  await workerPage.getByRole('button', { name: 'Analysis & decision', exact: true }).click()
  await expect(workerPage.getByRole('button', { name: 'Approve & release work', exact: true })).toHaveCount(0)
  await expect(workerPage.getByRole('button', { name: 'Analyze current report', exact: true })).toHaveCount(0)
  await openReport(engineerPage, original)
  await engineerPage.getByRole('button', { name: 'Analysis & decision', exact: true }).click()
  await engineerPage.getByRole('button', { name: 'Analyze current report', exact: true }).click()
  await expect(engineerPage.getByText('Analysis recorded against the current report version.', { exact: true })).toBeVisible()
  await expect(engineerPage.getByRole('button', { name: 'Approve & release work', exact: true })).toBeDisabled()
  await engineerPage.getByLabel('Decision / clarification note', { exact: true }).fill('Confirm injury status and equipment safe state before release.')
  await engineerPage.getByRole('button', { name: 'Return for clarification / changes', exact: true }).click()
  await workerPage.getByRole('button', { name: 'Refresh source', exact: true }).click()
  await workerPage.getByRole('button', { name: 'Revise report', exact: true }).click()
  const safetySelects = workerPage.locator('.form-grid select')
  await expect(safetySelects).toHaveCount(2)
  await safetySelects.nth(0).selectOption('none')
  await safetySelects.nth(1).selectOption('isolated')
  await workerPage.getByRole('button', { name: 'Save new report version', exact: true }).click()
  await engineerPage.getByRole('button', { name: 'Refresh source', exact: true }).click()
  await engineerPage.getByRole('button', { name: 'Analyze current report', exact: true }).click()
  await expect(engineerPage.getByText('Analysis recorded against the current report version.', { exact: true })).toBeVisible()
  await engineerPage.getByLabel('Decision / clarification note', { exact: true }).fill('Reviewed actual test source and accepted the controlled work record.')
  const reviewConfirmation = engineerPage.getByRole('checkbox', { name: /I independently reviewed source version/ })
  await expect(reviewConfirmation).toBeEnabled()
  await reviewConfirmation.check()
  await engineerPage.getByRole('button', { name: 'Approve & release work', exact: true }).click()
  await expect(engineerPage.getByRole('heading', { name: 'Approved by Priyanshu Chauhan', exact: true })).toBeVisible()
  await workerPage.getByRole('button', { name: 'Refresh source', exact: true }).click()
  await workerPage.getByRole('button', { name: /^Released work/ }).click()
  await workerPage.getByRole('button', { name: 'Begin released work', exact: true }).click()
  const steps = workerPage.locator('.work-checklist > li')
  for (let index = 0; index < await steps.count(); index++) {
    const step = steps.nth(index)
    await step.getByLabel('Execution notes', { exact: true }).fill(`Synthetic test observation for completed step ${index + 1}.`)
    await step.getByRole('checkbox', { name: 'Mark complete on save', exact: true }).check()
    await step.getByRole('button', { name: 'Save step record', exact: true }).click()
    await expect(step.getByRole('button', { name: 'Save step record', exact: true })).toBeDisabled()
  }
  await workerPage.getByLabel('Completion & handoff note', { exact: true }).fill('All synthetic acceptance work completed; independent inspection requested.')
  await workerPage.getByRole('button', { name: 'Submit for engineer verification', exact: true }).click()
  await expect(workerPage.getByText('Work is awaiting independent engineering verification. It is not closed yet.')).toBeVisible()
  await engineerPage.getByRole('button', { name: 'Refresh source', exact: true }).click()
  await engineerPage.getByRole('button', { name: /^Released work/ }).click()
  await engineerPage.getByLabel('Verification / return note', { exact: true }).fill('Independent acceptance check of all test work notes completed.')
  await engineerPage.getByRole('button', { name: 'Verify & close incident', exact: true }).click()
  await expect(engineerPage.locator('.detail-status .badge')).toHaveText('Closed')
  await worker.close(); await engineer.close(); await admin.dispose()
})
